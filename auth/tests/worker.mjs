import assert from 'node:assert/strict';
import { handle } from '../worker.mjs';
const origin = 'https://frame-editor-auth.lsellars5.workers.dev';
const env = { GITHUB_OAUTH_ID: 'test-id', GITHUB_OAUTH_SECRET: 'test-secret' };
const req = path => new Request(origin + path);
assert.equal((await handle(req('/'), {})).status, 200);
assert.equal((await handle(req('/auth?provider=github'), {})).status, 503);
assert.equal((await handle(req('/auth?provider=other'), env)).status, 400);
assert.equal((await handle(req('/auth?provider=github&site_id=other.example'), env)).status, 400);
assert.equal((await handle(new Request(origin+'/auth', {method:'POST'}), env)).status, 405);
assert.equal((await handle(new Request('https://other.example/auth'), env)).status, 404);
const auth = await handle(req('/auth?provider=github&site_id=lxkes-languages.github.io'), env);
assert.equal(auth.status, 302);
assert.equal(auth.headers.get('Cache-Control'), 'no-store');
const target = new URL(auth.headers.get('Location'));
assert.equal(target.origin, 'https://github.com');
assert.equal(target.searchParams.get('scope'), 'public_repo');
assert.equal(target.searchParams.get('code_challenge_method'), 'S256');
assert.equal(target.searchParams.get('state').length, 43);
const cookie = auth.headers.get('Set-Cookie');
assert.match(cookie, /Secure; HttpOnly; SameSite=Lax/);
const savedCookie = cookie.split(';')[0];
const state = target.searchParams.get('state');
const callback = stateValue => new Request(origin+'/callback?code=sample-code&state='+stateValue, {headers:{Cookie:savedCookie}});
let requests = [];
const api = async (url, options) => {
  requests.push({url, options});
  if (url.endsWith('/access_token')) return Response.json({access_token:'test-access-token',refresh_token:'never-return-this'});
  if (url.endsWith('/user')) return Response.json({login:'lxkes-languages'});
  return Response.json({permissions:{push:true}});
};
assert.equal((await handle(callback('wrong'), env, api)).status, 400);
assert.equal(requests.length, 0, 'Invalid state must never exchange a code');
const success = await handle(callback(state), env, api);
const html = await success.text();
assert.match(html, /authorization:github:success/);
assert.ok(html.includes('test-access-token'));
assert.ok(!html.includes('test-secret') && !html.includes('never-return-this'));
assert.ok(html.includes('event.origin !== origin') && html.includes('event.source !== window.opener'));
assert.ok(!html.includes('postMessage(\"*\"') && !html.includes(", '*')"));
assert.match(success.headers.get('Content-Security-Policy'), /frame-ancestors 'none'/);
assert.match(success.headers.get('Set-Cookie'), /Max-Age=0/);
const exchange = requests[0];
assert.equal(exchange.options.body.get('code_verifier').length, 43);
assert.equal(exchange.options.body.get('client_secret'), 'test-secret');
const denied = await handle(callback(state), env, async url => {
  if (url.endsWith('/access_token')) return Response.json({access_token:'denied-token'});
  return Response.json({login:'someone-else'});
});
const deniedHtml = await denied.text();
assert.match(deniedHtml, /authorization:github:error/);
assert.ok(!deniedHtml.includes('denied-token'));
const failure = await handle(callback(state), env, async () => {throw new Error('sensitive upstream failure')});
assert.ok(!(await failure.text()).includes('sensitive upstream failure'));
console.log('PASS: OAuth routing, setup state, CSRF rejection, PKCE, secure cookies, owner restriction, exact-origin messaging, secret exclusion and upstream failures.');
