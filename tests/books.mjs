import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { Script, runInNewContext } from 'node:vm';
const root=new URL('../',import.meta.url);
const read=name=>readFile(new URL(name,root),'utf8');
const base='https://lxkes-languages.github.io/frame-magazine/';
const content=runInNewContext(`${await read('content.js')}\nFRAMEContent;`,{URL,document:{baseURI:base}});
const [review]=content.normaliseStories({'a-book-review':{title:'A book worth reading',category:'Book Reviews',image:'/frame-magazine/uploads/book.jpg',alt:'Book cover',text:['My review'],date:'2026-10-30'}},base);
assert.equal(review.category,'Book Reviews');
assert.equal(review.id,'a-book-review');
const config=JSON.parse(await read('admin/config.json'));
assert.ok(config.collections.find(c=>c.name==='stories').fields.find(f=>f.name==='category').options.includes('Book Reviews'));
assert.equal(config.publish_mode,'editorial_workflow');
const data=JSON.parse(await read('_data/website.json'));
const website=runInNewContext(`${await read('website.js')}\nFRAMEWebsite;`,{URL,document:{baseURI:base}});
const settings=website.normalise(data,base);
assert.equal(settings.texts['navigation.books'],'Book Reviews');
assert.equal(settings.texts['books.heading'],'Book reviews');
assert.equal(settings.visibility.books,true);
assert.equal(website.normalise({visibility:{books:false}},base).visibility.books,false);
const html=await read('index.html');
assert.ok(html.includes('href="#books"'));
assert.ok(html.includes('id="books"'));
assert.ok(html.includes('class="story-grid book-grid"'));
assert.ok(html.includes('data-filter="books"'));
for(const path of ['content.js','website.js'])new Script(await read(path),{filename:path});
console.log('PASS: Book Reviews data, editor category, draft workflow, navigation, section, filter and editable visibility.');
