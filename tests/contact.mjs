import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { runInNewContext, Script } from 'node:vm';
const root = new URL('../', import.meta.url);
const read = name => readFile(new URL(name,root),'utf8');
const base='https://lxkes-languages.github.io/frame-magazine/';
const code=await read('website.js');
new Script(code);
const website=runInNewContext(`${code}\nFRAMEWebsite;`,{URL,document:{baseURI:base}});
const normalise=about=>website.normalise({about},base);
assert.equal(normalise({contact_url:'https://www.instagram.com/lukesellars_'}).contactHref,'https://www.instagram.com/lukesellars_');
assert.equal(normalise({contact_url:'https://example.com/contact'}).contactHref,'https://example.com/contact');
assert.equal(normalise({email:'hello@example.com'}).contactHref,'mailto:hello@example.com','Existing email settings remain compatible');
assert.equal(normalise({contact_url:'',email:'hello@example.com'}).contactHref,'','Clearing the new field hides the link');
for(const contact_url of ['javascript:alert(1)','data:text/html,test','https://user:password@example.com','http://example.com'])assert.equal(normalise({contact_url}).contactHref,'');
const data=JSON.parse(await read('_data/website.json'));
assert.equal(website.normalise(data,base).contactHref,data.about.contact_url);
const config=JSON.parse(await read('admin/config.json'));
const about=config.collections.find(c=>c.name==='website').files[0].fields.find(f=>f.name==='about');
assert.ok(about.fields.some(f=>f.name==='contact_url'));
assert.ok(!about.fields.some(f=>f.name==='email'));
assert.equal(config.publish_mode,'editorial_workflow');
console.log('PASS: Instagram and website links, legacy email compatibility, explicit hide, unsafe URLs, saved settings and CMS field.');
